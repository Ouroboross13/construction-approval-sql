-- =================================================================
-- 1. ТАБЛИЦА ПОЛЬЗОВАТЕЛЕЙ И СОГЛАСУЮЩИХ (USERS)
-- =================================================================
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(150) NOT NULL,
    role VARCHAR2(50) NOT NULL,            -- CONTRACTOR, SUPERVISOR, ENGINEER, MANAGER
    department VARCHAR2(100) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1))
);

-- =================================================================
-- 2. ТАБЛИЦА СТРОИТЕЛЬНЫХ ЗАЯВОК (REQUESTS)
-- =================================================================
CREATE TABLE requests (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id NUMBER NOT NULL REFERENCES users(user_id),
    construction_object VARCHAR2(200) NOT NULL,
    request_date DATE DEFAULT SYSDATE NOT NULL,
    current_status VARCHAR2(50) NOT NULL,   -- NEW, IN_PROGRESS, REJECTED, APPROVED
    current_approver_id NUMBER REFERENCES users(user_id)
);

-- =================================================================
-- 3. ИСТОРИЯ ЭТАПОВ СОГЛАСОВАНИЯ (APPROVAL_STAGES)
-- =================================================================
CREATE TABLE approval_stages (
    stage_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id NUMBER NOT NULL REFERENCES requests(request_id),
    approver_id NUMBER NOT NULL REFERENCES users(user_id),
    stage_name VARCHAR2(100) NOT NULL,     -- Сметный контроль, Технадзор, Главный инженер
    decision VARCHAR2(30),                 -- PENDING, APPROVED, REJECTED
    assigned_date DATE DEFAULT SYSDATE NOT NULL,
    decision_date DATE,
    comment_text VARCHAR2(1000)
);

-- =================================================================
-- 4. ИНДЕКСЫ ДЛЯ УСКОРЕНИЯ ВЫБОРКИ И ДЖОЙНОВ (ОПТИМИЗАЦИЯ EXPLAIN PLAN)
-- =================================================================
-- Ускорение поиска заявок конкретного согласующего
CREATE INDEX idx_req_approver ON requests(current_approver_id);

-- Ускорение фильтрации по статусу заявки
CREATE INDEX idx_req_status ON requests(current_status);

-- Ускорение соединения этапов с основной таблицей заявок
CREATE INDEX idx_stage_req_fk ON approval_stages(request_id);

-- Составной индекс для поиска незакрытых этапов конкретного согласующего
CREATE INDEX idx_stage_decision ON approval_stages(approver_id, decision);